type ConcreteCommandError = (typeof _COMMAND_ERROR_CODES)[number];

/** Closed union of all DO RPC wire error codes. */
export type CommandError = ConcreteCommandError | `undeclared:${string}`;

/** Registry of concrete wire codes — every idempotency const must appear here. */
export const COMMAND_ERROR_CODES = _COMMAND_ERROR_CODES satisfies readonly ConcreteCommandError[];

export const UNDECLARED_CONFIG_PREFIX = 'undeclared:' as const;

export function configUndeclared(key: string): `undeclared:${string}` {
  return `${UNDECLARED_CONFIG_PREFIX}${key}`;
}

export function isCommandError(value: string): value is CommandError {
  if (value.startsWith(UNDECLARED_CONFIG_PREFIX)) {
    return true;
  }
  return (COMMAND_ERROR_CODES as readonly string[]).includes(value);
}
